#!/usr/bin/env node
/**
 * Turn the raw TL3 extraction into the pairing module the player and authoring
 * tool consume. Run extract-tl3-pairings.mjs first.
 *
 * Two editorial decisions are applied here rather than carried forward blindly:
 *
 *   Uniform values are not pairing data. Every one of TL3's 21 sets specifies
 *   `line-height: 1.3em` for body text — identical across all of them. That
 *   makes it a global setting TL3 happened to put in the font files, not a
 *   characteristic of any pairing, and 1.3 is tight for a block of prose
 *   besides (WCAG 1.4.8 asks for 1.5 in AAA contexts; the player already
 *   defaults to 1.65). A pairing therefore carries only what genuinely varies
 *   between pairings: the families, the body size, and the headline's size
 *   ceiling, weight and casing.
 *
 *   Fallback stacks must end in a generic. A pairing's own fallbacks are
 *   preserved, but a generic family is appended when TL3 didn't supply one,
 *   because the generic is what maps to a system font covering the reader's
 *   script. For anything outside a pairing's `scripts` list, that fallback is
 *   what actually renders.
 *
 * The `knightlab` set is dropped: it pairs Salvo Serif Cond with Turnip RE,
 * both licensed faces not available on Google Fonts.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '../..');

const raw = JSON.parse(readFileSync(resolve(HERE, 'pairings.raw.json'), 'utf8'));
const manifest = JSON.parse(readFileSync(resolve(HERE, 'manifest.json'), 'utf8'));

const EXCLUDE = new Set(['knightlab']);
const SERIF = /serif|georgia|garamond|playfair|bitter|vollkorn|ledger|rufina|lustria|old standard|gentium|abril|bevan|slab/i;

const px = n => `${(n / 16).toFixed(4).replace(/0+$/, '').replace(/\.$/, '')}rem`;

function stack(family, fallback) {
  const parts = [family, ...fallback].filter(Boolean);
  const last = parts[parts.length - 1]?.toLowerCase();
  if (!['serif', 'sans-serif', 'monospace', 'cursive', 'fantasy'].includes(last)) {
    parts.push(SERIF.test(family) ? 'serif' : 'sans-serif');
  }
  return parts.map(p => (/\s/.test(p) && !/^[a-z-]+$/.test(p) ? `'${p}'` : p)).join(', ');
}

const out = raw
  .filter(p => !EXCLUDE.has(p.id))
  .map(p => {
    const set = manifest.sets[p.id];
    const tokens = {
      '--tl-font-heading': stack(p.heading.family, p.heading.fallback),
      '--tl-font-body': stack(p.body.family, p.body.fallback),
    };
    if (p.bodyPx && p.bodyPx !== 16) tokens['--tl-body-size'] = px(p.bodyPx);
    if (p.headingPx) tokens['--tl-headline-size'] = `clamp(1.2rem, 3cqi, ${px(p.headingPx)})`;
    if (p.headingWeight && p.headingWeight !== 700) tokens['--tl-headline-weight'] = String(p.headingWeight);
    if (p.headingTransform !== 'none') tokens['--tl-headline-transform'] = p.headingTransform;

    return {
      id: p.id,
      label: `${p.heading.family} + ${p.body.family}`,
      heading: p.heading.family,
      body: p.body.family,
      /* Scripts both faces cover. Anything else renders from the fallback. */
      scripts: p.scripts,
      /* Families needing a web font; empty means system fonts only. */
      webfonts: Object.keys(set.families),
      tokens,
    };
  });

const ts = `/*
 * Font pairings carried forward from TimelineJS 3.
 *
 * GENERATED by scripts/fonts/generate-pairings.mjs — do not edit by hand.
 * Source: ${manifest.source} (extracted ${manifest.generatedAt})
 *
 * A pairing is a set of --tl-* token values, nothing more. It does not load
 * anything: \`webfonts\` names the families a host must serve for the pairing to
 * render as designed, and \`scripts\` records which writing systems both of its
 * faces actually cover.
 *
 * That \`scripts\` list is the important one for an international audience. Most
 * of these families are Latin-and-maybe-Cyrillic only; a timeline written in a
 * script outside the list still renders, but from the stack's generic fallback
 * rather than the chosen face, per character. A pairing with no webfonts at all
 * ('system') inherits the reader's OS coverage, which is why it is the safe
 * default rather than the boring one.
 */

export interface FontPairing {
  id: FontPairingId;
  /** Human-readable "Heading + Body". */
  label: string;
  heading: string;
  body: string;
  /** Writing systems both faces cover; ['system'] means OS fonts, so all. */
  scripts: string[];
  /** Families the host must serve; empty for system-font pairings. */
  webfonts: string[];
  /** --tl-* values to apply. */
  tokens: Record<string, string>;
}

/** Every pairing id, as a union — this is what TLSettings.fontPairing accepts. */
export type FontPairingId =
${out.map(p => `  | '${p.id}'`).join('\n')};

export const FONT_PAIRINGS: FontPairing[] = ${JSON.stringify(out, null, 2)};

export const DEFAULT_PAIRING: FontPairingId = 'georgia-helvetica';

export function getPairing(id: string | undefined): FontPairing | undefined {
  if (!id) return undefined;
  return FONT_PAIRINGS.find(p => p.id === id);
}

/**
 * Whether a pairing's faces cover \`language\`'s script. Used to warn an author
 * that their chosen pairing will fall back rather than render as shown.
 */
export function coversLanguage(pairing: FontPairing, language: string): boolean {
  if (pairing.scripts.includes('system')) return true;
  const base = language.toLowerCase().split('-')[0];
  /*
   * Languages whose script is not Latin. Anything absent is assumed Latin —
   * a safe default given the long tail is overwhelmingly Latin-script
   * European languages, and a wrong guess here only costs a spurious warning.
   * Scripts no Google Latin/Cyrillic family covers (CJK, Arabic, Hebrew,
   * Thai, Indic) will never appear in a pairing's list, so they correctly
   * report as uncovered.
   */
  const SCRIPT_BY_LANG: Record<string, string> = {
    ru: 'cyrillic', uk: 'cyrillic', bg: 'cyrillic', sr: 'cyrillic', mk: 'cyrillic',
    be: 'cyrillic', kk: 'cyrillic', mn: 'cyrillic',
    el: 'greek', vi: 'vietnamese',
    hi: 'devanagari', mr: 'devanagari', ne: 'devanagari',
    ja: 'japanese', zh: 'chinese', ko: 'korean',
    ar: 'arabic', fa: 'arabic', ur: 'arabic',
    he: 'hebrew', th: 'thai', bn: 'bengali', ta: 'tamil',
    ka: 'georgian', hy: 'armenian', am: 'ethiopic', km: 'khmer', my: 'myanmar',
  };
  const needed = SCRIPT_BY_LANG[base] ?? 'latin';
  return pairing.scripts.includes(needed);
}
`;

writeFileSync(resolve(REPO, 'packages/core/src/fonts.ts'), ts);
console.log(`packages/core/src/fonts.ts — ${out.length} pairings`);
const sys = out.filter(p => !p.webfonts.length).length;
console.log(`  ${sys} system-only, ${out.length - sys} needing web fonts`);
